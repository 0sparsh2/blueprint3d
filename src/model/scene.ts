module BP3D.Model {
  /**
   * The Scene is a manager of Items and also links to a ThreeJS scene.
   */
  export class Scene {

    /** The associated ThreeJS scene. */
    private scene: THREE.Scene;

    /** */
    private items: Items.Item[] = [];

    /** */
    public needsUpdate = false;

    /** The Json loader. */
    private loader: THREE.JSONLoader;

    /** */
    private itemLoadingCallbacks = $.Callbacks();

    /** Item */
    private itemLoadedCallbacks = $.Callbacks();

    /** Item */
    private itemRemovedCallbacks = $.Callbacks();

    /**
     * Constructs a scene.
     * @param model The associated model.
     * @param textureDir The directory from which to load the textures.
     */
    constructor(private model: Model, private textureDir: string) {
      this.scene = new THREE.Scene();

      // init item loader
      this.loader = new THREE.JSONLoader();
      this.loader.crossOrigin = "";
    }

    /** Adds a non-item, basically a mesh, to the scene.
     * @param mesh The mesh to be added.
     */
    public add(mesh: THREE.Mesh) {
      this.scene.add(mesh);
    }

    /** Removes a non-item, basically a mesh, from the scene.
     * @param mesh The mesh to be removed.
     */
    public remove(mesh: THREE.Mesh) {
      this.scene.remove(mesh);
      Core.Utils.removeValue(this.items, mesh);
    }

    /** Gets the scene.
     * @returns The scene.
     */
    public getScene(): THREE.Scene {
      return this.scene;
    }

    /** Gets the items.
     * @returns The items.
     */
    public getItems(): Items.Item[] {
      return this.items;
    }

    /** Gets the count of items.
     * @returns The count.
     */
    public itemCount(): number {
      return this.items.length
    }

    /** Removes all items. */
    public clearItems() {
      var items_copy = this.items
      var scope = this;
      this.items.forEach((item) => {
        scope.removeItem(item, true);
      });
      this.items = []
    }

    /**
     * Removes an item.
     * @param item The item to be removed.
     * @param dontRemove If not set, also remove the item from the items list.
     */
    public removeItem(item: Items.Item, dontRemove?: boolean) {
      dontRemove = dontRemove || false;
      // use this for item meshes
      this.itemRemovedCallbacks.fire(item);
      item.removed();
      this.scene.remove(item);
      if (!dontRemove) {
        Core.Utils.removeValue(this.items, item);
      }
    }

    /**
     * Creates an item and adds it to the scene.
     * @param itemType The type of the item given by an enumerator.
     * @param fileName The name of the file to load.
     * @param metadata TODO
     * @param position The initial position.
     * @param rotation The initial rotation around the y axis.
     * @param scale The initial scaling.
     * @param fixed True if fixed.
     */
    public addItem(itemType: number, fileName: string, metadata, position: THREE.Vector3, rotation: number, scale: THREE.Vector3, fixed: boolean) {
      itemType = itemType || 1;
      if (scale == null && metadata && metadata.defaultScale != null) {
        var defaultScale = Number(metadata.defaultScale);
        scale = new THREE.Vector3(defaultScale, defaultScale, defaultScale);
      }
      var scope = this;
      var loaderCallback = function (geometry: THREE.Geometry, materials: THREE.Material[]) {
        var item = new (Items.Factory.getClass(itemType))(
          scope.model,
          metadata, geometry,
          new THREE.MeshFaceMaterial(materials),
          position, rotation, scale
        );
        item.fixed = fixed || false;
        scope.items.push(item);
        scope.add(item);
        item.initObject();
        scope.itemLoadedCallbacks.fire(item);
      }

      this.itemLoadingCallbacks.fire();
      if (/\.glb$/i.test(fileName)) {
        this.loadGLB(fileName, loaderCallback);
      } else {
        this.loader.load(
          fileName,
          loaderCallback,
          undefined // TODO_Ekki
        );
      }
    }

    /** Loads the single-mesh textured GLB assets generated by the local AI pipeline. */
    private loadGLB(fileName: string, callback: (geometry: THREE.Geometry, materials: THREE.Material[]) => void) {
      var request = new XMLHttpRequest();
      request.open("GET", fileName, true);
      request.responseType = "arraybuffer";
      request.onload = function () {
        if (request.status !== 0 && (request.status < 200 || request.status >= 300)) {
          throw new Error("Unable to load GLB asset: " + fileName);
        }

        var buffer = request.response as ArrayBuffer;
        var header = new DataView(buffer, 0, 12);
        if (header.getUint32(0, true) !== 0x46546c67) {
          throw new Error("Invalid GLB header: " + fileName);
        }

        var jsonLength = new DataView(buffer, 12, 4).getUint32(0, true);
        var jsonStart = 20;
        var jsonText = "";
        var jsonBytes = new Uint8Array(buffer, jsonStart, jsonLength);
        for (var i = 0; i < jsonBytes.length; i++) {
          jsonText += String.fromCharCode(jsonBytes[i]);
        }
        var gltf = JSON.parse(jsonText);
        var binHeader = 12 + 8 + jsonLength;
        var binLength = new DataView(buffer, binHeader, 4).getUint32(0, true);
        var binStart = binHeader + 8;
        var bin = buffer.slice(binStart, binStart + binLength);
        var primitive = gltf.meshes[0].primitives[0];
        var geometry = new THREE.Geometry();

        var readAccessor = function (accessorIndex: number): any[] {
          var accessor = gltf.accessors[accessorIndex];
          var view = gltf.bufferViews[accessor.bufferView];
          var componentSize = accessor.componentType === 5126 || accessor.componentType === 5125 ? 4 : (accessor.componentType === 5123 ? 2 : 1);
          var componentCount = accessor.type === "SCALAR" ? 1 : (accessor.type === "VEC2" ? 2 : (accessor.type === "VEC3" ? 3 : 4));
          var offset = (view.byteOffset || 0) + (accessor.byteOffset || 0);
          var stride = view.byteStride || componentSize * componentCount;
          var result = [];
          var viewData = new DataView(bin);
          for (var n = 0; n < accessor.count; n++) {
            var values = [];
            for (var c = 0; c < componentCount; c++) {
              var at = offset + n * stride + c * componentSize;
              if (accessor.componentType === 5126) values.push(viewData.getFloat32(at, true));
              else if (accessor.componentType === 5125) values.push(viewData.getUint32(at, true));
              else if (accessor.componentType === 5123) values.push(viewData.getUint16(at, true));
              else values.push(viewData.getUint8(at));
            }
            result.push(values);
          }
          return result;
        };

        var positions = readAccessor(primitive.attributes.POSITION);
        var uvs = primitive.attributes.TEXCOORD_0 == null ? [] : readAccessor(primitive.attributes.TEXCOORD_0);
        var indices = primitive.indices == null ? positions.map(function (_v, index) { return [index]; }) : readAccessor(primitive.indices);
        positions.forEach(function (p) { geometry.vertices.push(new THREE.Vector3(p[0], p[1], p[2])); });
        geometry.faceVertexUvs[0] = [];
        for (var f = 0; f + 2 < indices.length; f += 3) {
          var a = indices[f][0], b = indices[f + 1][0], c = indices[f + 2][0];
          geometry.faces.push(new THREE.Face3(a, b, c));
          geometry.faceVertexUvs[0].push(uvs.length ? [
            new THREE.Vector2(uvs[a][0], 1 - uvs[a][1]),
            new THREE.Vector2(uvs[b][0], 1 - uvs[b][1]),
            new THREE.Vector2(uvs[c][0], 1 - uvs[c][1])
          ] : []);
        }
        geometry.computeFaceNormals();
        geometry.computeVertexNormals();
        geometry.computeBoundingBox();
        // Some legacy Three.js builds fail to derive bounds for very large
        // imported geometries; glTF accessors carry authoritative min/max.
        var positionAccessor = gltf.accessors[primitive.attributes.POSITION];
        if (positionAccessor && positionAccessor.min && positionAccessor.max) {
          geometry.boundingBox = new THREE.Box3(
            new THREE.Vector3(positionAccessor.min[0], positionAccessor.min[1], positionAccessor.min[2]),
            new THREE.Vector3(positionAccessor.max[0], positionAccessor.max[1], positionAccessor.max[2])
          );
        }

        var material = new THREE.MeshPhongMaterial({ color: 0xffffff, side: THREE.DoubleSide });
        var materialIndex = primitive.material == null ? 0 : primitive.material;
        var gltfMaterial = gltf.materials && gltf.materials[materialIndex];
        var textureIndex = gltfMaterial && gltfMaterial.pbrMetallicRoughness && gltfMaterial.pbrMetallicRoughness.baseColorTexture && gltfMaterial.pbrMetallicRoughness.baseColorTexture.index;
        if (textureIndex != null && gltf.images && gltf.images[gltf.textures[textureIndex].source]) {
          var image = gltf.images[gltf.textures[textureIndex].source];
          var imageView = gltf.bufferViews[image.bufferView];
          var imageBytes = bin.slice(imageView.byteOffset || 0, (imageView.byteOffset || 0) + imageView.byteLength);
          var imageUrl = URL.createObjectURL(new Blob([imageBytes], { type: image.mimeType || "image/png" }));
          new THREE.TextureLoader().load(imageUrl, function (texture) {
            material.map = texture;
            material.needsUpdate = true;
            URL.revokeObjectURL(imageUrl);
          });
        }
        callback(geometry, [material]);
      };
      request.send(null);
    }
  }
}
